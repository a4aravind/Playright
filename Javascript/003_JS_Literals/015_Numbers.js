let decimal = 42; // Decimal representation
console.log(decimal); // Output: 42

let binaryNumber = 0b101010; // Binary representation of 42
console.log(binaryNumber); // Output: 42

let octalNumber = 0o52; // Octal representation of 42
console.log(octalNumber); // Output: 42

let hexNumber = 0x2A; // Hexadecimal representation of 42
console.log(hexNumber); // Output: 42


let float1 = 2.4; // Floating-point representation
console.log(float1); // Output: 2.4

let float2 = -2.4; // Negative floating-point number
console.log(float2); // Output: -2.4

let float3 = 2. ; // Scientific notation for 2400
console.log(float3); // Output: 2

let float4 = .2; // Scientific notation for 0.2
console.log(float4); // Output: 0.2


let exp1 = 1e3; // Scientific notation for 1000
console.log(exp1); // Output: 1000

let exp2 = 1.5e-3;
console.log(exp2); // Output: 0.0015

let exp3 = 1e2;
console.log(exp3); // Output: 100